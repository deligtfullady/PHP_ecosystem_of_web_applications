<?php

declare(strict_types=1);

namespace Tests\Providers;

final class CronProvider
{
    /**
     * [выражение, момент времени, ожидается ли срабатывание]
     * 2024-03-15 — пятница, 2024-03-17 — воскресенье, 2024-03-18 — понедельник.
     *
     * @return array<string, array{0: string, 1: string, 2: bool}>
     */
    public static function dueCases(): array
    {
        return [
            'каждую минуту' => ['* * * * *', '2024-03-15 10:30:00', true],
            'точное время — совпало' => ['30 10 * * *', '2024-03-15 10:30:00', true],
            'точное время — минута не совпала' => ['31 10 * * *', '2024-03-15 10:30:00', false],
            'шаг */15 — совпал' => ['*/15 * * * *', '2024-03-15 10:45:00', true],
            'шаг */15 — не совпал' => ['*/15 * * * *', '2024-03-15 10:50:00', false],
            'будни, рабочие часы — пятница 09:00' => ['0 9-17 * * 1-5', '2024-03-15 09:00:00', true],
            'будни, рабочие часы — воскресенье' => ['0 9-17 * * 1-5', '2024-03-17 09:00:00', false],
            'будни, рабочие часы — после 17' => ['0 9-17 * * 1-5', '2024-03-15 18:00:00', false],
            'список минут' => ['0,30 * * * *', '2024-03-15 10:30:00', true],
            'день и месяц — совпали' => ['0 0 1 1 *', '2024-01-01 00:00:00', true],
            'день и месяц — другой месяц' => ['0 0 1 1 *', '2024-02-01 00:00:00', false],
            'воскресенье как 7' => ['0 12 * * 7', '2024-03-17 12:00:00', true],
            'воскресенье как 0' => ['0 12 * * 0', '2024-03-17 12:00:00', true],
            'день месяца ИЛИ день недели — по числу' => ['0 12 15 * 1', '2024-03-15 12:00:00', true],
            'день месяца ИЛИ день недели — по дню недели' => ['0 12 15 * 1', '2024-03-18 12:00:00', true],
            'день месяца ИЛИ день недели — ни то ни другое' => ['0 12 15 * 1', '2024-03-19 12:00:00', false],
            'диапазон с шагом — совпал' => ['10-50/20 * * * *', '2024-03-15 10:30:00', true],
            'диапазон с шагом — не совпал' => ['10-50/20 * * * *', '2024-03-15 10:20:00', false],
        ];
    }

    /** @return array<string, array{0: string}> */
    public static function invalidExpressions(): array
    {
        return [
            'пустая строка' => [''],
            '4 поля' => ['* * * *'],
            '6 полей' => ['* * * * * *'],
            'минута 60' => ['60 * * * *'],
            'час 24' => ['* 24 * * *'],
            'день 0' => ['* * 0 * *'],
            'месяц 13' => ['* * * 13 *'],
            'день недели 8' => ['* * * * 8'],
            'буква вместо числа' => ['a * * * *'],
            'шаг 0' => ['*/0 * * * *'],
            'обратный диапазон' => ['5-1 * * * *'],
            'шаг у одиночного числа' => ['1/5 * * * *'],
            'отрицательное число' => ['-1 * * * *'],
            'пустой элемент списка' => ['1,,2 * * * *'],
        ];
    }
}
